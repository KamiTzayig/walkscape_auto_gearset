    print(f"Executing {len(jobs)} optimization permutations.")
    
    start_time = time.time()
    results = []

    with ProcessPoolExecutor(initializer=worker_init, initargs=(user_state_dict,)) as executor:
        progress_bar = tqdm(
            executor.map(process_job, jobs, chunksize=1), 
            total=len(jobs), 
            desc="Optimizing Gear",
            mininterval=0.5
        )
        
        for res in progress_bar:
            if res:
                results.append(res)

    if results:
        keys = results[0].keys()
        with open("benchmark_results.csv", "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=keys)
            writer.writeheader()
            writer.writerows(results)
            
        print(f"\nDone! Exported {len(results)} rows to benchmark_results.csv")
    else:
        print("\nNo valid results generated.")
        
    print(f"Total execution time: {round(time.time() - start_time, 2)} seconds")